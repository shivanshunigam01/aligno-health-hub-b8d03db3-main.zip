/**
 * Upload local hero banner assets to Cloudinary (axios + signed upload).
 * Writes src/lib/heroCloudinary.generated.ts for the app to consume.
 */
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import axios from "axios";
import dotenv from "dotenv";
import FormData from "form-data";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
dotenv.config({ path: path.join(root, ".env") });

const cloudName = process.env.CLOUDINARY_CLOUD_NAME;
const apiKey = process.env.CLOUDINARY_API_KEY;
const apiSecret = process.env.CLOUDINARY_API_SECRET;

if (!cloudName || !apiKey || !apiSecret) {
  console.error("Missing CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY, or CLOUDINARY_API_SECRET in .env");
  process.exit(1);
}

/** Slide order = homepage hero order (matches seedBanners titles). */
const HERO_FILES = [
  { file: "banner-move-freely.png", publicId: "aligno/hero/banner-move-freely" },
  { file: "banner-posture.png", publicId: "aligno/hero/banner-posture" },
  { file: "banner-active-living.png", publicId: "aligno/hero/banner-active-living" },
  { file: "banner-lifestyle-studio.jpg", publicId: "aligno/hero/banner-lifestyle-studio" },
];

function signUploadParams(params) {
  const sorted = Object.keys(params)
    .sort()
    .map((k) => `${k}=${params[k]}`)
    .join("&");
  return crypto.createHash("sha1").update(sorted + apiSecret).digest("hex");
}

async function uploadImage(absPath, publicId) {
  const timestamp = Math.round(Date.now() / 1000);
  const params = { timestamp, public_id: publicId, overwrite: "true", invalidate: "true" };
  const signature = signUploadParams(params);

  const form = new FormData();
  form.append("file", fs.createReadStream(absPath));
  form.append("api_key", apiKey);
  form.append("timestamp", String(timestamp));
  form.append("signature", signature);
  form.append("public_id", publicId);
  form.append("overwrite", "true");
  form.append("invalidate", "true");

  const { data } = await axios.post(
    `https://api.cloudinary.com/v1_1/${cloudName}/image/upload`,
    form,
    { headers: form.getHeaders(), maxBodyLength: Infinity, maxContentLength: Infinity },
  );

  return data.secure_url;
}

async function main() {
  const urls = {};
  for (const entry of HERO_FILES) {
    const abs = path.join(root, "public", "img", entry.file);
    if (!fs.existsSync(abs)) {
      console.warn(`Skip missing file: ${entry.file}`);
      continue;
    }
    console.log(`Uploading ${entry.file}…`);
    const url = await uploadImage(abs, entry.publicId);
    urls[entry.file] = url;
    console.log(`  → ${url}`);
  }

  const orderedUrls = HERO_FILES.map((e) => urls[e.file]).filter(Boolean);
  if (orderedUrls.length === 0) {
    console.error("No images uploaded.");
    process.exit(1);
  }

  const out = `/** Auto-generated by scripts/upload-hero-cloudinary.mjs — do not edit by hand */
export const HERO_CLOUDINARY_URLS: string[] = ${JSON.stringify(orderedUrls, null, 2)};

export const HERO_CLOUDINARY_BY_FILE: Record<string, string> = ${JSON.stringify(urls, null, 2)};
`;

  const outPath = path.join(root, "src", "lib", "heroCloudinary.generated.ts");
  fs.writeFileSync(outPath, out, "utf8");
  console.log(`\nWrote ${outPath}`);
  console.log("\nHero URLs:");
  orderedUrls.forEach((u, i) => console.log(`  [${i + 1}] ${u}`));
}

main().catch((err) => {
  console.error(err.response?.data || err);
  process.exit(1);
});